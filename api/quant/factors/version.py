"""팩터 산식 버전 — 측정 경계의 단일 출처 (2026-08-17 신설).

## 왜 이게 필요한가

`backtest_kr_price_axes.json`(2026-08-09)에서 본페로니 |t|≥2.73 을 통과한 축은
**volatility 4셀이 유일**하다 (IC 0.072~0.109 · |t| 4.95~6.52). 이 시스템에서 확증된
단 하나의 신호다. 그런데 팩터 산식은 계속 바뀐다:

| 날짜 | 변경 | 순위 영향 |
|---|---|---|
| 2026-08-16 | 부착 순서 교정 (문헌 팩터가 합산 뒤에 붙어 기여 0 이던 것) | 있음 |
| 2026-08-17 | 결측 하위축 재정규화 | **없음** (Spearman 1.000000 — 아핀 고정점이 50) |
| 대기 | beta 부분 채움 | **있음** (실측 Spearman 0.7936 · KR +16.8 vs US +0.0) |
| 대기 | 임계 배점 → z-score 동일가중 | 있음 (연속화로 구간 내 정보 복원) |

🚨 **버전 도장이 없으면 옛 확증이 어느 정의를 가리키는지 영구히 갈 수 없다.**
IC 를 집계할 때 경계 전후를 섞으면, 개선인지 정의 변경인지 판별이 불가능해진다.

## 어디에 찍는가 — 점수가 아니라 **측정 기록**에

`_compute_graham_score` · `_compute_canslim_score` 는 float 만 반환한다. 4개 팩터의
반환 형태를 바꾸고 그 소비처(fact.py + 백테스트 9개 모듈)를 전부 고치는 것은
이 목적에 과하다. 버전은 **점수의 속성이 아니라 관측의 속성**이므로,
예측 trail 과 백테스트 산출물이 도장을 찍는다.

## 언제 올리는가

**횡단면 순위를 바꾸는 변경**에서만 올린다. 순위가 보존되면(예: 8/17 재정규화 —
아핀 고정점이 결측군 상수 50 과 일치해 Spearman 1.000000) IC 가 불변이므로 같은 버전이다.
🚨 "코드를 고쳤으니 올린다" 가 아니다 — 그러면 경계가 무의미하게 잘게 쪼개진다.

올릴 때는 이 파일의 `FACTOR_VERSION` 과 `_HISTORY` 를 같이 갱신한다.
"""
from __future__ import annotations

# 🚨 순위를 바꾸는 변경에서만 올린다. 아래 _HISTORY 에 근거를 남긴다.
FACTOR_VERSION = "v1_binned_20260816"

_HISTORY = (
    # (버전, 발효일, 순위 영향, 근거)
    ("v1_binned_20260816", "2026-08-16",
     "있음 — 부착 순서 교정으로 문헌 4축이 처음 실제 채점에 들어감",
     "PREREG_BASELINE_V1_LITERATURE_2026_08_16.md · 문헌 27.8%→100% · LLM 29.6%→0%"),
    # 2026-08-17 결측 재정규화는 **버전을 올리지 않았다** — Spearman 1.000000 으로
    #   순위가 완전 보존됐다(아핀 old=0.6·new+20 의 고정점 50 = 결측군 상수).
    #   근거 = PREREG_QUANT_FACTOR_FIX_2026_08_16.md §재검증.
)


def factor_version() -> str:
    """현 팩터 산식 버전. 측정 기록에 찍는다."""
    return FACTOR_VERSION


def version_history() -> tuple:
    """버전 이력 — 각 경계가 왜 생겼는지(순위 영향 포함)."""
    return _HISTORY
